const names = new Intl.DisplayNames("es", { type: "region" });
const data = Object.entries(specs)
  .map(([code, [regionLabel, currency, timeZone, timeZones = [timeZone]]]) => {
    const source = allCountries.find((country) => country[1] === code);
    if (!source) throw new Error(`Missing country ${code}`);
    let regions =
      overrides[code] ||
      source[2].map(([name]) => renames[`${code}:${name}`] || name);
    if (code === "PA") regions.push("Naso Tjër Di");
    if (code === "BZ")
      regions = regions.map((name) => name.replace(/ District$/, ""));
    regions = regions.sort((a, b) => a.localeCompare(b, "es"));
    if (new Set(regions).size !== regions.length)
      throw new Error("Duplicate region: " + code);
    for (const zone of timeZones)
      new Intl.DateTimeFormat("es", { timeZone: zone });
    return {
      code,
      name: code === "PR" ? "Puerto Rico (territorio)" : names.of(code),
      territory: code === "PR",
      regionLabel,
      currency,
      timeZone,
      timeZones,
      regions,
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name, "es"));
fs.writeFileSync("data/latam.json", JSON.stringify(data, null, 2) + "\n");
